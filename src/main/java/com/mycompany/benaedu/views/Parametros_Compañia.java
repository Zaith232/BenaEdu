private void cargarTablaParametros() {
        DefaultTableModel modelo = new DefaultTableModel(
            new Object[][] {}, 
            new String[] {"Compañía", "Año", "Periodo", "Póliza", "Orden de", "Remisión", "Rec.Pago", "Orden de Comp.", "Aut.Vtas.", "Aut.Compras", "Usuario", "Fecha Mod.", "Hora Mod."}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; 
            }
        };
        tblPCompañia.setModel(modelo);

        try {
            ConDB db = new ConDB();
            Connection con = db.Conectar();

            if (con != null) {
                // Consulta con los campos reales de tgpram
                String sql = "SELECT CIAACT, ANO, NPER, NPOL, ORDVEN, NUMREM, CONPAGSIG, CONCOMP, AUTFAC, AUTCOM, USER, FEAC, HOAC FROM tgpram";
                PreparedStatement ps = con.prepareStatement(sql);
                ResultSet rs = ps.executeQuery();

                while (rs.next()) {
                    Object[] fila = new Object[13]; 
                    fila[0] = rs.getString("CIAACT");
                    fila[1] = rs.getString("ANO");
                    fila[2] = rs.getString("NPER");
                    fila[3] = rs.getString("NPOL");
                    fila[4] = rs.getString("ORDVEN");
                    fila[5] = rs.getString("NUMREM");
                    fila[6] = rs.getString("CONPAGSIG");
                    fila[7] = rs.getString("CONCOMP");
                    fila[8] = rs.getString("AUTFAC");
                    fila[9] = rs.getString("AUTCOM");
                    fila[10] = rs.getString("USER");
                    fila[11] = rs.getString("FEAC");
                    fila[12] = rs.getString("HOAC");
                    modelo.addRow(fila);
                }
                rs.close(); ps.close(); db.Cerrar();
                
                adaptarTamañoColumnas();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar la tabla de Parámetros: " + e.getMessage());
        }
    }

    private void adaptarTamañoColumnas() {
        tblPCompañia.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_OFF); 
        for (int i = 0; i < tblPCompañia.getColumnCount(); i++) {
            javax.swing.table.TableColumn columna = tblPCompañia.getColumnModel().getColumn(i);
            int anchoPreferido = 60; 
            java.awt.Component compCabecera = tblPCompañia.getTableHeader().getDefaultRenderer()
                    .getTableCellRendererComponent(tblPCompañia, columna.getHeaderValue(), false, false, 0, i);
            anchoPreferido = Math.max(anchoPreferido, compCabecera.getPreferredSize().width + 10);
            columna.setPreferredWidth(anchoPreferido); 
        }
    }

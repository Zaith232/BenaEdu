    private void btnDeletePCompañiaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeletePCompañiaActionPerformed
    int fila = tblPCompañia.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una Compañía para eliminar sus parámetros.");
            return;
        }

        String cia = tblPCompañia.getValueAt(fila, 0).toString();
        
        int resp = JOptionPane.showConfirmDialog(this, "¿Seguro que deseas eliminar los parámetros de la compañía " + cia + "?", "Confirmar Eliminación", JOptionPane.YES_NO_OPTION);
        
        if (resp == JOptionPane.YES_OPTION) {
            try {
                ConDB db = new ConDB();
                Connection con = db.Conectar();
                if (con != null) {
                    PreparedStatement ps = con.prepareStatement("DELETE FROM tgpram WHERE CIAACT = ?");
                    ps.setString(1, cia);
                    if (ps.executeUpdate() > 0) {
                        JOptionPane.showMessageDialog(this, "Parámetros eliminados correctamente.");
                        cargarTablaParametros(); 
                    }
                    ps.close(); db.Cerrar();
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeletePCompañiaActionPerformed

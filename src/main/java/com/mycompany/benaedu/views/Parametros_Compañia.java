                        ps.setInt(1, anio);
                        ps.setInt(2, periodo);
                        ps.setInt(3, poliza);
                        ps.setInt(4, recPago);
                        ps.setString(5, cveImp);
                        ps.setInt(6, ordVen);
                        ps.setInt(7, remision);
                        ps.setInt(8, ordComp);
                        ps.setString(9, autFac);
                        ps.setString(10, autCom);
                        ps.setString(11, moneda);
                        ps.setString(12, metPago);
                        ps.setString(13, cia);

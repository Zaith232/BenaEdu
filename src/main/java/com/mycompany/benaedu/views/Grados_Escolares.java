    private void btnDeleteGEscolarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteGEscolarActionPerformed
        int fila = tblGEscolares.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona un grado escolar para eliminar.");
            return;
        }

        String cia = tblGEscolares.getValueAt(fila, 0).toString();
        String cc = tblGEscolares.getValueAt(fila, 1).toString();
        String secc = tblGEscolares.getValueAt(fila, 2).toString();
        String grado = tblGEscolares.getValueAt(fila, 3).toString();
        String desc = tblGEscolares.getValueAt(fila, 4).toString();

        int resp = JOptionPane.showConfirmDialog(this, "¿Eliminar el grado " + desc + "?", "Confirmar Eliminación", JOptionPane.YES_NO_OPTION);

        if (resp == JOptionPane.YES_OPTION) {
            try {
                ConDB db = new ConDB();
                Connection con = db.Conectar();
                if (con != null) {
                    // Borramos utilizando las 4 llaves maestras
                    String sql = "DELETE FROM tesgrad WHERE CIA = ? AND CC = ? AND SECC = ? AND CGRAD = ?";
                    PreparedStatement ps = con.prepareStatement(sql);
                    ps.setString(1, cia);
                    ps.setString(2, cc);
                    ps.setString(3, secc);
                    ps.setString(4, grado);

                    if (ps.executeUpdate() > 0) {
                        JOptionPane.showMessageDialog(this, "Grado escolar eliminado.");
                        cargarTablaGrados();
                    } else {
                        JOptionPane.showMessageDialog(this, "No se encontró el registro para eliminar.");
                    }
                    ps.close();
                    db.Cerrar();
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeleteGEscolarActionPerformed


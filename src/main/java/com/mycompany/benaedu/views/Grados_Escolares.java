    private void cargarTablaGrados() {
        // 1. Arreglamos las columnas de la tabla para coincidir con tu diseño exacto y la BD
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[][]{},
                new String[]{"Compañía", "Centro Costos", "Sección", "Grado", "Descripción", "Usuario", "Fec Ult Act", "Hora Ult Act"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblGEscolares.setModel(modelo);

        // 2. Cargamos los datos reales de la tabla tesgrad
        try {
            ConDB db = new ConDB();
            Connection con = db.Conectar();

            if (con != null) {
                String sql = "SELECT CIA, CC, SECC, CGRAD, DGRAD, USER, FEAC, HOAC FROM tesgrad";
                PreparedStatement ps = con.prepareStatement(sql);
                ResultSet rs = ps.executeQuery();

                while (rs.next()) {
                    Object[] fila = new Object[8];
                    fila[0] = rs.getString("CIA");
                    fila[1] = rs.getString("CC");
                    fila[2] = rs.getString("SECC");
                    fila[3] = rs.getString("CGRAD");
                    fila[4] = rs.getString("DGRAD");
                    fila[5] = rs.getString("USER");
                    fila[6] = rs.getString("FEAC");
                    fila[7] = rs.getString("HOAC");
                    modelo.addRow(fila);
                }
                rs.close();
                ps.close();
                db.Cerrar();

                adaptarTamañoColumnas();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar la tabla: " + e.getMessage());
        }
    }

    // --- MÉTODO PARA AUTO-AJUSTAR ANCHO DE COLUMNAS ---
    private void adaptarTamañoColumnas() {
        tblGEscolares.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_OFF);

        for (int i = 0; i < tblGEscolares.getColumnCount(); i++) {
            javax.swing.table.TableColumn columna = tblGEscolares.getColumnModel().getColumn(i);
            int anchoPreferido = 50;

            java.awt.Component compCabecera = tblGEscolares.getTableHeader().getDefaultRenderer()
                    .getTableCellRendererComponent(tblGEscolares, columna.getHeaderValue(), false, false, 0, i);
            anchoPreferido = Math.max(anchoPreferido, compCabecera.getPreferredSize().width + 10);

            for (int r = 0; r < tblGEscolares.getRowCount(); r++) {
                javax.swing.table.TableCellRenderer renderizador = tblGEscolares.getCellRenderer(r, i);
                java.awt.Component c = tblGEscolares.prepareRenderer(renderizador, r, i);
                anchoPreferido = Math.max(anchoPreferido, c.getPreferredSize().width + 15);
            }
            columna.setPreferredWidth(anchoPreferido);
        }
    }


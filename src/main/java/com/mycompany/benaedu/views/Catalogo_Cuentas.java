private void cargarTablaCuentas() {
        DefaultTableModel modelo = (DefaultTableModel) tblCCuentas.getModel();
        modelo.setRowCount(0); 

        try {
            ConDB db = new ConDB();
            Connection con = db.Conectar();

            if (con != null) {
                // Traemos los 18 campos exactos que tienes en tu diseño de columnas
                String sql = "SELECT CIA, CCTA, CDES, CNIV, TCTA, STIP, CMAY, CC01, CC02, CC03, CC04, CC05, CC06, CC, AUX, USER, FEAC, HOAC FROM tmctas";
                PreparedStatement ps = con.prepareStatement(sql);
                ResultSet rs = ps.executeQuery();

                while (rs.next()) {
                    Object[] fila = new Object[18]; 
                    fila[0] = rs.getString("CIA");
                    fila[1] = rs.getString("CCTA");
                    fila[2] = rs.getString("CDES");
                    fila[3] = rs.getString("CNIV");
                    fila[4] = rs.getString("TCTA"); 
                    fila[5] = rs.getString("STIP"); 
                    fila[6] = rs.getString("CMAY"); 
                    fila[7] = rs.getString("CC01"); // Clasif 1
                    fila[8] = rs.getString("CC02"); // Clasif 2
                    fila[9] = rs.getString("CC03"); // Clasif 3
                    fila[10] = rs.getString("CC04"); // Clasif 4
                    fila[11] = rs.getString("CC05"); // Clasif 5
                    fila[12] = rs.getString("CC06"); // Clasif 6
                    fila[13] = rs.getString("CC");   // Centro de cuenta
                    fila[14] = rs.getString("AUX");  // Subcuenta
                    fila[15] = rs.getString("USER");
                    fila[16] = rs.getString("FEAC");
                    fila[17] = rs.getString("HOAC");

                    modelo.addRow(fila);
                }
                rs.close(); ps.close(); db.Cerrar();
                
                // ¡Llamamos a la magia para ajustar los anchos!
                adaptarTamañoColumnas();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar el Catálogo de Cuentas: " + e.getMessage());
        }
    }


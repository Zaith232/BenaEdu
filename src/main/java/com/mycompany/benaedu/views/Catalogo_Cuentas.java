    private void btnDeleteCCuentasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteCCuentasActionPerformed
       int fila = tblCCuentas.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una cuenta para eliminar.");
            return;
        }

        String cia = tblCCuentas.getValueAt(fila, 0).toString();
        String ccta = tblCCuentas.getValueAt(fila, 1).toString();
        String desc = tblCCuentas.getValueAt(fila, 2).toString();
        
        int resp = JOptionPane.showConfirmDialog(this, 
            "¿Seguro que deseas eliminar la cuenta:\n" + ccta + " - " + desc + "?", 
            "Confirmar Eliminación", JOptionPane.YES_NO_OPTION);
        
        if (resp == JOptionPane.YES_OPTION) {
            try {
                ConDB db = new ConDB();
                Connection con = db.Conectar();
                if (con != null) {
                    String sql = "DELETE FROM tmctas WHERE CIA = ? AND CCTA = ?";
                    PreparedStatement ps = con.prepareStatement(sql);
                    ps.setString(1, cia);
                    ps.setString(2, ccta);
                    
                    if (ps.executeUpdate() > 0) {
                        JOptionPane.showMessageDialog(this, "Cuenta contable eliminada correctamente.");
                        cargarTablaCuentas(); 
                    } else {
                        JOptionPane.showMessageDialog(this, "No se encontró la cuenta para eliminar.");
                    }
                    ps.close(); db.Cerrar();
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeleteCCuentasActionPerformed


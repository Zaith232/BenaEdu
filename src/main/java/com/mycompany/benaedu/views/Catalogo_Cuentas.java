    private void adaptarTamañoColumnas() {
        tblCCuentas.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_OFF); // Apagamos el ajuste automático por defecto
        
        for (int i = 0; i < tblCCuentas.getColumnCount(); i++) {
            javax.swing.table.TableColumn columna = tblCCuentas.getColumnModel().getColumn(i);
            int anchoPreferido = 50; // Ancho mínimo
            
            // Evaluamos el ancho del título de la columna
            java.awt.Component compCabecera = tblCCuentas.getTableHeader().getDefaultRenderer()
                    .getTableCellRendererComponent(tblCCuentas, columna.getHeaderValue(), false, false, 0, i);
            anchoPreferido = Math.max(anchoPreferido, compCabecera.getPreferredSize().width + 10);
            
            // Evaluamos el ancho del contenido de cada fila
            for (int r = 0; r < tblCCuentas.getRowCount(); r++) {
                javax.swing.table.TableCellRenderer renderizador = tblCCuentas.getCellRenderer(r, i);
                java.awt.Component c = tblCCuentas.prepareRenderer(renderizador, r, i);
                anchoPreferido = Math.max(anchoPreferido, c.getPreferredSize().width + 15); // +15 de margen visual
            }
            
            columna.setPreferredWidth(anchoPreferido); // Aplicamos el ancho perfecto
        }
    }
